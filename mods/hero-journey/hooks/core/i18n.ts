/**
 * A língua da HUD. A opção do mod manda; em `auto`, vale a configuração
 * `language` do Claude Code e depois o LANG do sistema; sem nenhum dos dois,
 * a primeira mensagem da pessoa decide; por fim, inglês.
 */
export const resolveLang = (
  option: unknown,
  claudeLanguage: unknown,
  systemLang: string | undefined,
  firstPrompt: string | undefined,
): Lang => {
  if (option === 'pt-BR') return 'pt'
  if (option === 'en') return 'en'
  const named = typeof claudeLanguage === 'string' ? claudeLanguage.trim().toLowerCase() : ''
  if (/^(pt|portugu)/.test(named)) return 'pt'
  // Outra língua do Claude (japonês, espanhol...): a HUD só fala pt e en.
  if (named !== '') return 'en'
  if (systemLang !== undefined && /^pt/i.test(systemLang)) return 'pt'
  if (systemLang !== undefined && /^en/i.test(systemLang)) return 'en'
  if (firstPrompt !== undefined && looksPortuguese(firstPrompt)) return 'pt'
  return 'en'
}

const PT_WORDS =
  /(?<![\p{L}])(não|você|vc|para|pra|que|com|uma|um|isso|esse|essa|está|tá|então|também|arquivo|faça|faz|leia|fale|da|dos|das|os|roda|rodar|testes|veja|projeto|quantas|quantos|tem|como|mas|aqui|agora|vamos|pode|preciso|quero|meu|minha|ele|ela|seu|sua|pelo|pela|por favor|obrigad\p{L}*)(?![\p{L}])/giu

/** Acento já basta; sem acento, duas ocorrências de palavras portuguesas (repetidas valem: "para… para…"). */
export const looksPortuguese = (text: string) => /[ãõçáéíóúâêô]/i.test(text) || (text.match(PT_WORDS) ?? []).length >= 2
